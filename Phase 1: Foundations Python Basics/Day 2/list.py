my_list = [10, 20, 30, 40, 50]
print(my_list[0])  # Output: 10

print(my_list[2])  # Output: 30
print(my_list[-1]) # Output: 50
my_list[1] = 25
print(my_list)     # Output: [10, 25, 30, 40, 50]

# list slicing 
print(my_list[1:4])  # Output: [25, 30, 40]
print(my_list[:3])   # Output: [10, 25, 30]

